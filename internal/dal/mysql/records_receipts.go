// AppendRawDLR files one receipt of a message that does not close it: a
// progress word, a part that does not close its long message, the account's
// own answer (a `policy:` row). A row in its message's receipts table
// (dlr_<company>_<day of the message>), counted in summary_dlr.
func (s *Store) AppendRawDLR(ctx context.Context, ref model.RecordRef, entryJSON string) error {
	var e rawDLREntry
	_ = json.Unmarshal([]byte(entryJSON), &e)
	return s.appendReceipt(ctx, ref, e, false)
}

// AppendRawDLROnce is AppendRawDLR for a caller that may be writing the same
// receipt a second time (the DB worker, whose task can be seen twice after a
// stop): when the message already has a row with the same status, error code
// and raw text, nothing is written.
func (s *Store) AppendRawDLROnce(ctx context.Context, ref model.RecordRef, entryJSON string) error {
	var e rawDLREntry
	_ = json.Unmarshal([]byte(entryJSON), &e)
	return s.appendReceipt(ctx, ref, e, true)
}

func (s *Store) appendReceipt(ctx context.Context, ref model.RecordRef, e rawDLREntry, once bool) error {
	table := dlrOf(ref)
	if err := s.ensureRecords(ctx, table); err != nil {
		return err
	}
	return s.inTx(ctx, func(tx *sql.Tx) error {
		msg, err := readMessage(ctx, tx, ref)
		if err != nil {
			return err
		}
		if !msg.found {
			return sql.ErrNoRows
		}
		if once {
			var n int
			err := tx.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+table+
				" WHERE msg_id=? AND COALESCE(status,'')=? AND COALESCE(error_code,'')=? AND COALESCE(raw,'')=?",
				ref.MsgID, e.Status, e.ErrorCode, e.Raw).Scan(&n)
			if err != nil && !isNoSuchTable(err) {
				return err
			}
			if n > 0 {
				return nil
			}
		}
		d := newSums()
		if _, err := insertReceiptTx(ctx, tx, ref, table, msg, e, false, d); err != nil {
			return err
		}
		return s.flushSums(ctx, tx, d)
	})
}

// insertReceiptTx writes one receipt's row in tx, with what it adds to the
// receipts' summary. closes: the row is to close its message (final_of); a
// message closed already gets the row as recorded only (mine=false). A row
// recorded only books nothing, and keeps no price.
func insertReceiptTx(ctx context.Context, tx *sql.Tx, ref model.RecordRef, table string, msg messageOf, e rawDLREntry, closes bool, d *sums) (mine bool, err error) {
	// delivered_at is when the receipt reached us; done_date is when the
	// vendor says the message reached the phone (NULL when it did not say).
	var done any
	if t, err := time.Parse(time.RFC3339, e.DoneAt); err == nil {
		done = t.UTC()
	}
	vendor := msg.vendor
	insert := func(final any, sell, buy int64, fx float64) error {
		// The row that closes its message carries the status it closes with
		// (a per-vendor rule may have renamed the vendor's outcome; its word
		// stays in stat), as the summaries count it.
		status := e.Status
		if final != nil && e.FinalStatus != "" {
			status = e.FinalStatus
		}
		_, err := tx.ExecContext(ctx, "INSERT INTO "+table+" ("+receiptRowCols+") VALUES "+receiptRowValue,
			ref.MsgID, msg.account, receiptSource(e.Source, e.Raw), nz(vendor), nsStr(e.VendorMsgID), nzInt(e.Part), nil,
			nsStr(status), nsStr(e.Stat),
			nsStr(trunc(e.ErrorCode, 32)), nsStr(trunc(e.Raw, 512)), final, nsStr(deployment.ID()), done,
			nz(sell), nz(buy), nsFx(fx), ackAtArg(arrivedAt(e)))
		return err
	}
	if closes && !msg.rejected {
		err := insert(ref.MsgID, e.SellRateID, e.BuyRateID, e.FX)
		switch {
		case err == nil:
			mine = true
		case isDupEntry(err):
			// Closed already by another receipt: this one is evidence.
			err = insert(nil, 0, 0, 0)
		}
		if err != nil {
			return false, err
		}
	} else {
		sell, buy := e.SellRateID, e.BuyRateID
		if e.RecordedOnly || msg.rejected && closes {
			sell, buy = 0, 0 // a receipt recorded only booked nothing
		}
		if err := insert(nil, sell, buy, e.FX); err != nil {
			return false, err
		}
	}
	d.addReceipt(arrivedAt(e), msg.account, vendor, e.Stat, e.ErrorCode)
	if mine && msg.row.msgID != "" {
		r := msg.row
		r.status = e.Status
		if fs := e.FinalStatus; fs != "" {
			r.status = fs
		}
		d.addMT(r.key, r.outcome(), 1)
		if err := closeOpen(ctx, tx, ref.MsgID); err != nil {
			return mine, err
		}
	}
	return mine, nil
}

// arrivedAt is when a receipt reached us: the time it carries, else now.
func arrivedAt(e rawDLREntry) time.Time {
	if t, err := time.Parse(time.RFC3339Nano, e.At); err == nil && !t.IsZero() {
		return t
	}
	return time.Now()
}

// RecordState says whether a message's record is written, and its status
// worked out (its final receipt, else sent with a vendor answer, else
// queued; a refusal at submission of before 27 Oct is its own status).
// [dlr.RecordChecker]
//
// A receipt matched by its facts in Redis may come before its record (the
// vendor role's write is a batch away, or the DB worker is behind, or the
// record is queued on the other deployment): the receipt path asks this
// before it changes anything, and keeps a receipt whose record is not there
// to be applied again (go-live test 18 Oct 2026: it was answered and lost).
func (s *Store) RecordState(ctx context.Context, ref model.RecordRef) (status string, found bool, err error) {
	var st sql.NullString
	err = s.db.QueryRowContext(ctx, "SELECT COALESCE(f.status,"+submittedOr(subOf(ref))+") FROM "+mtOf(ref)+" m LEFT JOIN "+dlrOf(ref)+
		" f ON f.final_of = m.msg_id WHERE m.msg_id=?", ref.MsgID).Scan(&st)
	if isNoSuchTable(err) {
		// No receipt or submission table yet for that day: the message, alone.
		err = s.db.QueryRowContext(ctx, "SELECT "+submittedOr(s.subIfThere(ctx, s.db, ref))+" FROM "+mtOf(ref)+" m WHERE m.msg_id=?", ref.MsgID).Scan(&st)
	}
	if err == sql.ErrNoRows || isNoSuchTable(err) {
		err = s.db.QueryRowContext(ctx, "SELECT status FROM "+rejectsOf(ref)+" WHERE msg_id=?", ref.MsgID).Scan(&st)
	}
	if err == sql.ErrNoRows || isNoSuchTable(err) {
		return "", false, nil
	}
	if err != nil {
		return "", false, err
	}
	return st.String, true, nil
}

// CloseWithReceipt files a final receipt of a message and, when this receipt
// is the one that closes it, marks it so (dlr_.final_of), in ONE transaction
// with the summaries. mine says this call closed it. [dlr.ReceiptCloser]
//
// mayClose=false: another receipt holds the message's closing mark (Redis),
// so this one is only recorded. A message that is closed already is only
// recorded too, whatever mayClose says: the unique key on final_of says so.
// A receipt recorded only books nothing and keeps no price. A message with no
// record answers sql.ErrNoRows and nothing is written.
func (s *Store) CloseWithReceipt(ctx context.Context, ref model.RecordRef, st model.Status, vendorMsgID, errorCode, entryJSON string, mayClose bool) (mine bool, err error) {
	return s.closeWithReceipt(ctx, ref, st, vendorMsgID, errorCode, entryJSON, mayClose, false)
}

// CloseWithReceiptOnce is CloseWithReceipt for a task that may be seen twice
// (the DB worker): a row of this receipt there already (same message, status,
// error code and raw text) leaves everything as it is.
func (s *Store) CloseWithReceiptOnce(ctx context.Context, ref model.RecordRef, st model.Status, vendorMsgID, errorCode, entryJSON string, mayClose bool) (mine bool, err error) {
	return s.closeWithReceipt(ctx, ref, st, vendorMsgID, errorCode, entryJSON, mayClose, true)
}

func (s *Store) closeWithReceipt(ctx context.Context, ref model.RecordRef, st model.Status, vendorMsgID, errorCode, entryJSON string, mayClose, once bool) (mine bool, err error) {
	var e rawDLREntry
	_ = json.Unmarshal([]byte(entryJSON), &e)
	if e.VendorMsgID == "" {
		e.VendorMsgID = vendorMsgID
	}
	if e.Status == "" {
		e.Status = string(st)
	}
	if string(st) != e.Status && st.IsTerminal() {
		e.FinalStatus = string(st) // a per-vendor rule renamed the outcome
	}
	table := dlrOf(ref)
	if err := s.ensureRecords(ctx, table); err != nil {
		return false, err
	}
	err = s.inTx(ctx, func(tx *sql.Tx) error {
		mine = false
		msg, err := readMessage(ctx, tx, ref)
		if err != nil {
			return err
		}
		if !msg.found {
			return sql.ErrNoRows
		}
		if once {
			var n int
			err := tx.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+table+
				" WHERE msg_id=? AND COALESCE(status,'')=? AND COALESCE(error_code,'')=? AND COALESCE(raw,'')=?",
				ref.MsgID, e.Status, e.ErrorCode, e.Raw).Scan(&n)
			if err != nil && !isNoSuchTable(err) {
				return err
			}
			if n > 0 {
				return nil
			}
		}
		closes := mayClose && st.IsTerminal()
		e.RecordedOnly = !closes
		d := newSums()
		if mine, err = insertReceiptTx(ctx, tx, ref, table, msg, e, closes, d); err != nil {
			return err
		}
		return s.flushSums(ctx, tx, d)
	})
	return mine, err
}

// BillNote is what a message's final receipt books from: its charge mark,
// kept with it in open_msgs while it waits (hot/0074). The logs keep no money
// (issue 16); with Redis the note travels with the receipt facts
// (dlr.Facts.Bill) and open_msgs is empty. Without Redis this was "" for
// every message, so no receipt fee was ever booked (BUG-RR-02, 2 Nov 2026).
// The row is read before the close that removes it (dlr billJob, then
// closeRecord).
func (s *Store) BillNote(ctx context.Context, ref model.RecordRef) (string, error) {
	if !OpenMessagesInMySQL() || ref.MsgID == "" {
		return "", nil
	}
	var bill sql.NullString
	err := s.db.QueryRowContext(ctx, "SELECT bill FROM open_msgs WHERE msg_id = ?", ref.MsgID).Scan(&bill)
	if err == sql.ErrNoRows {
		return "", nil
	}
	if err != nil {
		return "", err
	}
	return bill.String, nil
}
