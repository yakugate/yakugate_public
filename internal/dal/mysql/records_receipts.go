// receiptRowCols are the columns of a receipt row; the last is the receipt's
// arrival, given as Unix seconds with milliseconds.
const receiptRowCols = `msg_id,account_id,source,vendor_id,vendor_msg_id,part,attempt,status,stat,error_code,raw,final_of,deployment_id,done_date,
	sell_rate_id,buy_rate_id,fx_rate,delivered_at`

// The sources of a receipt row (hot/0072; Saleem, 27 Oct 2026: "the dlr
// which are generated by us should be marked as system generated").
const (
	SourceVendor = "vendor" // a vendor's receipt
	SourceSystem = "system" // made by the gateway: a policy's answer, our own ACCEPTD, the end of a message no vendor kept, the blackhole's outcome
)

// receiptSource is a receipt row's source: the one it was given, else system
// for a `policy:` row (the account's answer, which is ours), else vendor.
func receiptSource(given, raw string) string {
	switch given {
	case SourceVendor, SourceSystem:
		return given
	}
	if strings.HasPrefix(raw, "policy:") {
		return SourceSystem
	}
	return SourceVendor
}

// ownStat is the word of a receipt the gateway makes when a message ends at
// submission (issue 23's standard words): out of tries UNDELIV, validity over
// EXPIRED, a vendor's refusal REJECTD; else the word for the status.
func ownStat(st, code string) string {
	switch code {
	case "MAX_ATTEMPTS_REACHED", "MAX_ATTEMPTS":
		return "UNDELIV"
	case "VALIDITY_EXPIRED", "EXPIRED":
		return "EXPIRED"
	}
	if st == string(model.StatusFailed) || st == string(model.StatusRejected) {
		if code != "" {
			return "REJECTD"
		}
	}
	return statForStatus(st)
}

var receiptRowValue = valuesFor(receiptRowCols, 1)

// writeSubmitReceipts files the receipts the gateway makes at submission
// (source system): the gateway's own ACCEPTD of a message an SMPP vendor took,
// and the receipt that CLOSES a message final at submission (final_of) — the
// blackhole's outcome, or the end of a message no vendor kept, with why. Its
// outcome is counted on the summary row the message was counted in: its
// vendor's when a vendor took it, else its acceptance's.
func (s *Store) writeSubmitReceipts(ctx context.Context, x dbtx, dlrTable string, recs []TerminalRecord, d *sums, now time.Time) error {
	var sb strings.Builder
	args := make([]any, 0, len(recs)*18)
	for i, r := range recs {
		m := r.Msg
		st := string(orStatus(m.Status))
		if st == string(model.StatusRejected) {
			st = string(model.StatusFailed)
		}
		final := finalStatus(st)
		code := clipReason(orStr(r.ErrorCode, m.ErrorCode), 32)
		var closes, vendor, raw any
		stat := statForStatus(st)
		if final {
			closes = m.ID
			if r.AckAt.IsZero() {
				stat = ownStat(st, code)
				raw = nsStr(clipReason(m.ErrorText, 512))
			}
		}
		if !r.AckAt.IsZero() {
			vendor = nz(m.VendorID)
		}
		if i > 0 {
			sb.WriteByte(',')
		}
		sb.WriteString(receiptRowValue)
		args = append(args, m.ID, m.AccountID, SourceSystem, vendor, nsStr(r.VendorMsgID), nil, attemptOf(r), st,
			stat, nsStr(code), raw, closes,
			// The gateway that wrote this receipt: the one that sent it.
			nsStr(orStr(m.SentDeploymentID, m.DeploymentID)), nil, nil, nil, nil, ackAtArg(now))
		vid := m.VendorID
		if r.AckAt.IsZero() {
			vid = 0
		}
		d.addReceipt(now, m.AccountID, vid, stat, code)
		if final {
			row := acceptedRowOf(m, now)
			if !r.AckAt.IsZero() {
				row = submittedRowOf(m, r.AckAt, now)
			}
			row.status = st
			d.addMT(row.key, row.outcome(), 1)
		}
	}
	_, err := x.ExecContext(ctx, "INSERT INTO "+dlrTable+" ("+receiptRowCols+") VALUES "+sb.String(), args...)
	return err
}

